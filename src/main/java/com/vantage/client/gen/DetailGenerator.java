package com.vantage.client.gen;

import com.vantage.Vantage;
import com.vantage.client.LodSession;
import com.vantage.client.ingest.RegionImporter;
import com.vantage.core.SectionKey;
import com.vantage.gen.WorldGenSandbox;
import com.vantage.net.ChunkSkin;
import com.vantage.net.DetailService;
import com.vantage.util.WorkerPool;
import com.vantage.world.ChunkStates;
import com.vantage.world.ColumnSource;
import com.vantage.world.PaletteDecoder;
import net.minecraft.core.Holder;
import net.minecraft.core.Registry;
import net.minecraft.core.registries.Registries;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.chunk.LevelChunkSection;
import net.minecraft.world.level.chunk.PalettedContainerRO;
import org.jetbrains.annotations.Nullable;

import java.util.IdentityHashMap;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicLong;
import java.util.function.Supplier;

/**
 * Replaces the approximate distant terrain near the player with real terrain, generated by
 * {@link WorldGenSandbox}: actual trees, plants, rocks and snow, block for block what Minecraft
 * would generate there (minus buildings). Explored chunks are never touched; they stay as the
 * player left them.
 *
 * <p>The planner asks for the fine sections it draws; work goes in units of one level-2
 * section column (8×8 chunks, one sandbox batch), nearest first, on its own low-priority threads.
 */
public final class DetailGenerator implements Detail {
    /** One unit of work: the chunks under one section column of this level. */
    private static final int UNIT_LEVEL = 2;
    private static final int UNIT_CHUNKS = WorldGenSandbox.INNER;
    private static final int MAX_QUEUED = 32;

    private final LodSession session;
    private final WorldGenSandbox sandbox;
    private final WorkerPool pool;
    private final Registry<Biome> clientBiomes;
    private final Supplier<@Nullable RegionImporter> importer;
    private final double maxDistance;
    private final Set<Long> queued = ConcurrentHashMap.newKeySet();
    private final Set<Long> done = ConcurrentHashMap.newKeySet();
    private final AtomicLong chunks = new AtomicLong();
    private final AtomicLong nanos = new AtomicLong();
    private final ThreadLocal<PaletteDecoder> decoders = ThreadLocal.withInitial(PaletteDecoder::new);
    private final ThreadLocal<Map<Holder<Biome>, Holder<Biome>>> biomeMaps = ThreadLocal.withInitial(IdentityHashMap::new);
    private volatile boolean closed;
    private volatile boolean failed;

    public DetailGenerator(LodSession session, WorldGenSandbox sandbox, int threads, double maxDistance, Registry<Biome> clientBiomes,
                           Supplier<@Nullable RegionImporter> importer) {
        this.session = session;
        this.sandbox = sandbox;
        this.pool = new WorkerPool("Vantage terrain", threads);
        this.maxDistance = maxDistance;
        this.clientBiomes = clientBiomes;
        this.importer = importer;
    }

    /** Planner thread: section {@code key} is drawn (or wanted) at {@code distance} blocks. */
    @Override
    public void request(long key, double distance) {
        int level = SectionKey.level(key);
        if (this.closed || this.failed || level > UNIT_LEVEL || distance > this.maxDistance) {
            return;
        }
        int shift = UNIT_LEVEL - level;
        long unit = pack(SectionKey.x(key) >> shift, SectionKey.z(key) >> shift);
        if (this.done.contains(unit) || this.queued.size() >= MAX_QUEUED || !this.queued.add(unit)) {
            return;
        }
        this.pool.submit(distance, () -> this.run(unit));
    }

    @Override
    public int queued() {
        return this.queued.size();
    }

    @Override
    public long chunks() {
        return this.chunks.get();
    }

    @Override
    public String describe() {
        return String.format(java.util.Locale.ROOT, "real terrain %d chunks (%.1f ms each), %d queued", this.chunks(), this.averageMillis(), this.queued());
    }

    /** Average milliseconds of work per generated chunk. */
    @Override
    public double averageMillis() {
        long n = this.chunks.get();
        return n == 0 ? 0 : this.nanos.get() / 1e6 / n;
    }

    @Override
    public void close() {
        this.closed = true;
        this.pool.close();
        Vantage.LOGGER.info("Real terrain: {} chunks, {}", this.chunks.get(), this.sandbox.stats());
    }

    public String stats() {
        return this.sandbox.stats();
    }

    private void run(long unit) {
        try {
            if (this.closed) {
                return;
            }
            int minX = unpackX(unit) * UNIT_CHUNKS;
            int minZ = unpackZ(unit) * UNIT_CHUNKS;
            // The camera may have moved on since this was asked for.
            double cx = (minX + UNIT_CHUNKS / 2.0) * 16 - this.session.camX();
            double cz = (minZ + UNIT_CHUNKS / 2.0) * 16 - this.session.camZ();
            if (Math.sqrt(cx * cx + cz * cz) > this.maxDistance + UNIT_CHUNKS * 16) {
                return;
            }
            if (!this.needed(minX, minZ)) {
                this.done.add(unit);
                return;
            }
            long t0 = System.nanoTime();
            int stored = 0;
            ServerLevel level = this.sandbox.level();
            if (this.fromServerCache(level, unit, minX, minZ)) {
                // Made earlier for a friend playing in this game.
                this.done.add(unit);
                return;
            }
            boolean share = DetailService.sharing(level);
            for (WorldGenSandbox.Chunk c : this.sandbox.generate(minX, minZ)) {
                if (this.closed) {
                    return;
                }
                if (share) {
                    // Friends playing in this game get it from here instead of making it again.
                    int slot = (c.pos().x & (UNIT_CHUNKS - 1)) | (c.pos().z & (UNIT_CHUNKS - 1)) << 4;
                    DetailService.offer(level, c.pos().x, c.pos().z, ChunkSkin.encode(ChunkSkin.of(c.chunk()), level.getMinBuildHeight(),
                            c.bottom(), slot, 0, level.registryAccess().registryOrThrow(Registries.BIOME)));
                }
                if (this.wanted(c.pos().x, c.pos().z) && this.session.ingestGenerated(this.toSource(c))) {
                    stored++;
                }
            }
            this.chunks.addAndGet(stored);
            this.nanos.addAndGet(System.nanoTime() - t0);
            this.done.add(unit);
        } catch (Throwable t) {
            if (!this.failed) {
                this.failed = true;
                Vantage.LOGGER.error("Detailed distant terrain failed and is off for this session", t);
            }
        } finally {
            this.queued.remove(unit);
        }
    }

    /** Stores the unit from skins the server made for other players, if it has them all. */
    private boolean fromServerCache(ServerLevel level, long unit, int minX, int minZ) {
        byte[][] skins = new byte[UNIT_CHUNKS * UNIT_CHUNKS][];
        for (int i = 0; i < skins.length; i++) {
            int cx = minX + i % UNIT_CHUNKS;
            int cz = minZ + i / UNIT_CHUNKS;
            if (this.wanted(cx, cz)) {
                skins[i] = DetailService.cached(level, cx, cz);
                if (skins[i] == null) {
                    return false;
                }
            }
        }
        BlockState stone = this.sandbox.stone();
        Holder<Biome> plains = this.clientBiomes.getHolderOrThrow(net.minecraft.world.level.biome.Biomes.PLAINS);
        for (byte[] skin : skins) {
            if (skin == null) {
                continue;
            }
            io.netty.buffer.ByteBuf buf = io.netty.buffer.Unpooled.wrappedBuffer(skin);
            ChunkSkin.Decoded d = ChunkSkin.decode(buf, Math.floorDiv(minX, UNIT_CHUNKS), Math.floorDiv(minZ, UNIT_CHUNKS), UNIT_CHUNKS,
                    level.getMinBuildHeight(), level.getSectionsCount(), stone, this.clientBiomes, plains, level.dimensionType().hasSkyLight());
            if (this.session.ingestGenerated(d.source())) {
                this.chunks.incrementAndGet();
            }
        }
        return true;
    }

    private boolean needed(int minX, int minZ) {
        for (int z = 0; z < UNIT_CHUNKS; z++) {
            for (int x = 0; x < UNIT_CHUNKS; x++) {
                if (this.wanted(minX + x, minZ + z)) {
                    return true;
                }
            }
        }
        return false;
    }

    /** False for chunks that are already real or generated, or that the save's import will bring. */
    private boolean wanted(int cx, int cz) {
        if (this.session.chunkStates().get(cx, cz) != ChunkStates.NONE) {
            return false;
        }
        RegionImporter imp = this.importer.get();
        return imp == null || !imp.pendingAt(cx << 4, cz << 4);
    }

    /** Minecraft's sections as they are, with solid rock under the generated band. */
    private ColumnSource toSource(WorldGenSandbox.Chunk c) {
        LevelChunkSection[] sections = c.chunk().getSections();
        ColumnSource src = new ColumnSource(c.pos().x, c.pos().z, sections.length, c.skyLight() != null);
        PaletteDecoder decoder = this.decoders.get();
        int first = c.chunk().getSectionIndex(c.bottom());
        for (int i = sections.length - 1; i >= 0; i--) {
            LevelChunkSection s = sections[i];
            if (i < first) {
                // Not generated, and never seen.
                src.sections[i] = new ColumnSource.Section(new BlockState[]{c.stone()}, null, src.sections[first].biomes(), null, null);
                continue;
            }
            Holder<Biome>[] cells = this.biomeCells(s);
            byte[] sky = c.skyLight() == null ? null : c.skyLight()[i];
            if (s.hasOnlyAir()) {
                src.sections[i] = new ColumnSource.Section(new BlockState[]{Blocks.AIR.defaultBlockState()}, null, cells, sky, null);
            } else {
                decoder.decode(s.getStates());
                src.sections[i] = new ColumnSource.Section(decoder.palette(), decoder.indices(), cells, sky, null);
            }
        }
        return src;
    }

    @SuppressWarnings("unchecked")
    private Holder<Biome>[] biomeCells(LevelChunkSection s) {
        PalettedContainerRO<Holder<Biome>> b = s.getBiomes();
        Map<Holder<Biome>, Holder<Biome>> biomeMap = this.biomeMaps.get();
        Holder<Biome>[] cells = new Holder[64];
        for (int y = 0; y < 4; y++) {
            for (int z = 0; z < 4; z++) {
                for (int x = 0; x < 4; x++) {
                    // The client has its own copy of the biome registry; tints come from that one.
                    cells[(y << 4) | (z << 2) | x] = biomeMap.computeIfAbsent(b.get(x, y, z), this::clientBiome);
                }
            }
        }
        return cells;
    }

    private Holder<Biome> clientBiome(Holder<Biome> server) {
        return server.unwrapKey().flatMap(this.clientBiomes::getHolder).<Holder<Biome>>map(h -> h).orElse(server);
    }

    private static long pack(int x, int z) {
        return (long) x << 32 | (z & 0xFFFFFFFFL);
    }

    private static int unpackX(long unit) {
        return (int) (unit >> 32);
    }

    private static int unpackZ(long unit) {
        return (int) unit;
    }
}
